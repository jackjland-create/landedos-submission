import { readFile } from "node:fs/promises";
import { headers } from "next/headers";
import { notFound } from "next/navigation";
import { ClarityReporting } from "@/components/clarity-reporting";
import { parseClarityQuery } from "@/lib/reports/clarity";
import { parseTimedClarityArtifact } from "@/lib/reports/timed-report-artifact.server";

export const dynamic = "force-dynamic";
export const metadata = {
  title: "Isolated retained report rendering",
  robots: { index: false, follow: false },
};

export default async function Page({
  params,
  searchParams,
}: {
  params: Promise<{ state: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const host = (await headers()).get("host");
  if (
    process.env.NODE_ENV !== "development" ||
    process.env.VERCEL_ENV ||
    !/^(localhost|127\.0\.0\.1):\d+$/.test(host ?? "") ||
    process.env.ENABLE_VISUAL_FIXTURES !== "1"
  )
    notFound();
  const { state } = await params;
  if (
    ![
      "ready",
      "missing-context",
      "error",
      "permission",
      "loading",
      "empty",
    ].includes(state)
  )
    notFound();
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(await searchParams))
    if (typeof value === "string") query.set(key, value);
  // Fixed synthetic artifact generated by the authenticated isolated rehearsal.
  // No environment credential, private SQL reader or live account fallback.
  if (state !== "ready")
    return (
      <ClarityReporting
        initialQuery={parseClarityQuery(query)}
        state={
          state === "missing-context"
            ? "error"
            : (state as "error" | "permission" | "loading" | "empty")
        }
        fixture={null}
        economics={{}}
        sourceMode="isolated-issued"
      />
    );
  let props: ReturnType<typeof parseTimedClarityArtifact> | null = null;
  try {
    props = parseTimedClarityArtifact(
      JSON.parse(
        await readFile("/private/tmp/landed-timed-report-clarity.json", "utf8"),
      ),
    );
  } catch {
    // Source read/validation failure only; rendering is outside this boundary.
  }
  if (!props)
    return (
      <ClarityReporting
        initialQuery={parseClarityQuery(query)}
        state="error"
        fixture={null}
        economics={{}}
        sourceMode="isolated-issued"
      />
    );
  query.set("version", String(props.fixture.selectedVersion.version));
  return (
    <ClarityReporting
      {...props}
      initialQuery={parseClarityQuery(query)}
      state="ready"
    />
  );
}
